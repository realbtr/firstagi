# Полный корпус
ALL_SERIAL_TEXTS: List[str] = SITUATION_TEXTS + ARC_TEXTS


def situation_of(text: str) -> str:
    """Вернуть тип ситуации для текста, или 'arc'/'unknown'."""
    for name, texts in SITUATION_FAMILIES.items():
        if text in texts:
            return name
    for arc in EPISODE_ARCS:
        if text in arc:
            return "arc"
    return "unknown"


def contains_character(text: str, char: str) -> bool:
    return char in text


def character_distribution(texts: List[str]) -> Dict[str, int]:
    """Подсчитать вхождения персонажей в тексты."""
    return {c: sum(1 for t in texts if contains_character(t, c))
            for c in CHARACTERS}


def corpus_stats() -> Dict:
    char_dist = character_distribution(ALL_SERIAL_TEXTS)
    return {
        "situation_texts": len(SITUATION_TEXTS),
        "arc_texts": len(ARC_TEXTS),
        "total": len(ALL_SERIAL_TEXTS),
        "situations": len(SITUATION_FAMILIES),
        "characters": char_dist,
        "texts_per_situation": {k: len(v) for k, v in SITUATION_FAMILIES.items()},
    }


