# Самый простой текст для реанимации (resource критически низкий)
_RESCUE_TEXT = "да нет да нет да нет да нет"


class TextCorpus:
    """
    Корпус текстов для обучения.

    Предоставляет тексты 4 уровней сложности.
    """

    def __init__(self) -> None:
        self._indices: Dict[int, int] = {1: 0, 2: 0, 3: 0, 4: 0}

    # ------------------------------------------------------------------

    def get_level(self, n: int) -> List[str]:
        """Получить все тексты указанного уровня (1-4)."""
        if n not in _CORPUS:
            raise ValueError(f"Уровень {n} не существует. Допустимы: 1-4.")
        return list(_CORPUS[n])

    def random_text(self, level: Optional[int] = None) -> str:
        """
        Получить случайный текст.

        Если level=None — выбирается случайный уровень равновероятно.
        """
        if level is None:
            level = random.randint(1, 4)
        texts = self.get_level(level)
        return random.choice(texts)

    def next_text(self, level: int) -> str:
        """
        Получить следующий текст уровня по очереди (циклически).
        Удобно для систематического прохода по корпусу.
        """
        texts = self.get_level(level)
        idx = self._indices[level] % len(texts)
        self._indices[level] = (idx + 1) % len(texts)
        return texts[idx]

    def easy_rescue(self) -> str:
        """Вернуть наипростейший текст для реанимации умирающей модели."""
        return _RESCUE_TEXT

    def level_count(self, level: int) -> int:
        """Количество текстов на уровне."""
        return len(self.get_level(level))

    def __repr__(self) -> str:
        total = sum(len(v) for v in _CORPUS.values())
        return f"TextCorpus(levels=4, total_texts={total})"
